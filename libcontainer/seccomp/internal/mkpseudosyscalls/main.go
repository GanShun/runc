//go:build linux && cgo && seccomp

// Command mkpseudosyscalls generates the multiplexor table the cgo-free seccomp
// compiler uses for the socket and System V IPC syscalls.
//
// On the architectures that multiplex those calls (x86, mips, ppc, s390, ...),
// libseccomp does not filter the name directly. It resolves the name to a
// negative pseudo-syscall number and, in abi_rule_add(), emits *two* rules:
//
//   - one on the multiplexor (socketcall(2) or ipc(2)) with argument 0 set to
//     the subcall number, which is (-pseudo) % 100 for the socket family and
//     (-pseudo) % 200 for the ipc family;
//   - one on the architecture's flat syscall number, for kernels new enough to
//     have a direct syscall.
//
// The Go compiler has to emit both, and it has to know the same table. That
// table is extracted here from libseccomp itself -- the negative numbers come
// back from seccomp_syscall_resolve_name_arch() -- so it cannot drift from the
// libseccomp it was measured against. The names are the ones in the Go table
// (syscalls_linux.go), because a name the Go table does not have is dropped by
// the compiler anyway; the multiplexor numbers come from that same table.
//
// Usage (from the runc checkout, with libseccomp available):
//
//	CGO_ENABLED=1 go run -tags seccomp ./libcontainer/seccomp/internal/mkpseudosyscalls
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	libseccomp "github.com/seccomp/libseccomp-golang"
)

// archPairs maps the generated table's SCMP_ARCH_* keys to libseccomp's own
// architecture tokens. It is the same list namecov uses.
var archPairs = []struct {
	goName string
	scmp   libseccomp.ScmpArch
}{
	{"SCMP_ARCH_X86", libseccomp.ArchX86},
	{"SCMP_ARCH_X86_64", libseccomp.ArchAMD64},
	{"SCMP_ARCH_X32", libseccomp.ArchX32},
	{"SCMP_ARCH_ARM", libseccomp.ArchARM},
	{"SCMP_ARCH_AARCH64", libseccomp.ArchARM64},
	{"SCMP_ARCH_LOONGARCH64", libseccomp.ArchLOONGARCH64},
	{"SCMP_ARCH_MIPS", libseccomp.ArchMIPS},
	{"SCMP_ARCH_MIPS64", libseccomp.ArchMIPS64},
	{"SCMP_ARCH_MIPS64N32", libseccomp.ArchMIPS64N32},
	{"SCMP_ARCH_MIPSEL", libseccomp.ArchMIPSEL},
	{"SCMP_ARCH_MIPSEL64", libseccomp.ArchMIPSEL64},
	{"SCMP_ARCH_MIPSEL64N32", libseccomp.ArchMIPSEL64N32},
	{"SCMP_ARCH_PPC", libseccomp.ArchPPC},
	{"SCMP_ARCH_PPC64", libseccomp.ArchPPC64},
	{"SCMP_ARCH_PPC64LE", libseccomp.ArchPPC64LE},
	{"SCMP_ARCH_RISCV64", libseccomp.ArchRISCV64},
	{"SCMP_ARCH_S390", libseccomp.ArchS390},
	{"SCMP_ARCH_S390X", libseccomp.ArchS390X},
}

// The pseudo-syscall ranges libseccomp uses, from seccomp-syscalls.h and
// syscalls.c. A number in the socket range is multiplexed through socketcall(2)
// with subcall = (-nr) % 100; one in the ipc range through ipc(2) with
// subcall = (-nr) % 200.
const (
	socketLow, socketHigh = -120, -100
	ipcLow, ipcHigh       = -224, -200
)

// entry is the generator's local copy of one generated pseudoSyscall.
type entry struct {
	mux     uint32
	subcall uint32
}

var (
	archRe  = regexp.MustCompile(`^\t"(SCMP_ARCH_[A-Z0-9_]+)": \{$`)
	entryRe = regexp.MustCompile(`^\t\t"([a-zA-Z0-9_]+)":\s+(\d+),$`)
)

func main() {
	tablesFile := flag.String("tables", "libcontainer/seccomp/syscalls_linux.go",
		"path to the generated Go syscall tables")
	out := flag.String("o", "libcontainer/seccomp/pseudosyscalls_linux.go",
		"output file (default stdout)")
	flag.Parse()

	tables, err := parseTables(*tablesFile)
	if err != nil {
		fatal(err)
	}
	ma, mi, mu := libseccomp.GetLibraryVersion()

	var buf bytes.Buffer
	fmt.Fprintf(&buf, `//go:build linux

// Code generated by internal/mkpseudosyscalls. DO NOT EDIT.
//
// Extracted from libseccomp %d.%d.%d. See internal/mkpseudosyscalls for how
// the numbers are derived.

package seccomp

// pseudoSyscall is one syscall name an architecture multiplexes through a
// multiplexor: libseccomp emits a rule on the multiplexor's number with
// argument 0 equal to subcall, in addition to the name's flat syscall number,
// and the cgo-free compiler matches it.

type pseudoSyscall struct {
	// mux is the syscall number of the multiplexor (socketcall(2) or ipc(2)).
	mux uint32
	// subcall is the value argument 0 must equal to select the subcall.
	subcall uint32
}

// pseudoSyscalls maps a SCMP_ARCH_* name to the syscall names it multiplexes.
// An architecture with no entry has no multiplexor and is filtered directly.

var pseudoSyscalls = map[string]map[string]pseudoSyscall{
`, ma, mi, mu)

	archNames := make([]string, 0, len(archPairs))
	byArch := make(map[string]map[string]entry)
	for _, p := range archPairs {
		table, ok := tables[p.goName]
		if !ok {
			continue
		}
		// socketcall and ipc are the only multiplexors libseccomp rewrites
		// through, and only an architecture whose own table has them can use
		// the rewrite.
		mux := map[string]uint32{}
		if n, ok := table["socketcall"]; ok {
			mux["socketcall"] = n
		}
		if n, ok := table["ipc"]; ok {
			mux["ipc"] = n
		}
		if len(mux) == 0 {
			continue
		}

		entries := map[string]entry{}
		for name := range table {
			if name == "socketcall" || name == "ipc" {
				continue
			}
			nr, err := libseccomp.GetSyscallFromNameByArch(name, p.scmp)
			if err != nil {
				// Not a name libseccomp resolves on this architecture. The
				// compiler drops such a rule anyway (divergence 4 in
				// docs/seccomp-go-vs-libseccomp.md); it just is not in the
				// pseudo table.
				continue
			}
			n := int32(nr)
			switch {
			case n >= socketLow && n <= socketHigh:
				entries[name] = entry{mux: mux["socketcall"], subcall: uint32((-n) % 100)}
			case n >= ipcLow && n <= ipcHigh:
				entries[name] = entry{mux: mux["ipc"], subcall: uint32((-n) % 200)}
			}
		}
		if len(entries) == 0 {
			continue
		}
		byArch[p.goName] = entries
		archNames = append(archNames, p.goName)
	}
	sort.Strings(archNames)

	for _, arch := range archNames {
		entries := byArch[arch]
		names := make([]string, 0, len(entries))
		for name := range entries {
			names = append(names, name)
		}
		sort.Strings(names)

		fmt.Fprintf(&buf, "\t%q: {\n", arch)
		for _, name := range names {
			e := entries[name]
			fmt.Fprintf(&buf, "\t\t%q: {mux: %d, subcall: %d},\n", name, e.mux, e.subcall)
		}
		fmt.Fprintf(&buf, "\t},\n")
	}
	fmt.Fprintf(&buf, "}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fatal(fmt.Errorf("formatting generated source: %w", err))
	}
	if *out == "" {
		os.Stdout.Write(src)
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d architectures, libseccomp %d.%d.%d)\n",
		*out, len(archNames), ma, mi, mu)
}

// parseTables reads the generated syscallNumbers map out of syscalls_linux.go.
// A regex is enough: the file is generated and its shape is fixed.
func parseTables(path string) (map[string]map[string]uint32, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	tables := map[string]map[string]uint32{}
	var arch string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		if m := archRe.FindStringSubmatch(line); m != nil {
			arch = m[1]
			tables[arch] = map[string]uint32{}
			continue
		}
		if m := entryRe.FindStringSubmatch(line); m != nil && arch != "" {
			n, err := strconv.ParseUint(m[2], 10, 32)
			if err != nil {
				return nil, fmt.Errorf("%s: %q: %w", path, line, err)
			}
			tables[arch][m[1]] = uint32(n)
			continue
		}
		if strings.TrimSpace(line) == "}," && arch != "" {
			arch = ""
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(tables) == 0 {
		return nil, fmt.Errorf("%s: no tables parsed; is it the generated file?", path)
	}
	return tables, nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "mkpseudosyscalls:", err)
	os.Exit(1)
}
